/**
 * Cancel a pending booking
 */
export async function cancelBooking(
  bookingId: string,
  userId: string,
  reason?: string
): Promise<{ success: boolean; error: string | null }> {
  try {
    const { error } = await supabase
      .from('bookings')
      .update({
        status: 'cancelled',
        cancelled_at: new Date().toISOString(),
        cancelled_by: userId,
        cancellation_reason: reason || 'Cancelled by customer',
        updated_at: new Date().toISOString(),
      })
      .eq('id', bookingId)
      .in('status', ['pending', 'accepted']); // Can only cancel if pending or accepted

    if (error) {
      return { success: false, error: error.message };
    }

    return { success: true, error: null };
  } catch (err: any) {
    return { success: false, error: err.message };
  }
}

/**
 * Update booking with increased price (retry after timeout)
 */
export async function retryBookingWithIncreasedPrice(
  bookingId: string,
  newTipAmount: number,
  newFareMultiplier: number
): Promise<{ success: boolean; error: string | null }> {
  try {
    // First get the current booking to calculate new payout
    const { data: booking, error: fetchError } = await supabase
      .from('bookings')
      .select('total_fare')
      .eq('id', bookingId)
      .single();

    if (fetchError || !booking) {
      return { success: false, error: 'Booking not found' };
    }

    const newDriverPayout = (booking.total_fare * newFareMultiplier) + newTipAmount;

    const { error } = await supabase
      .from('bookings')
      .update({
        tip_amount: newTipAmount,
        fare_multiplier: newFareMultiplier,
        driver_payout: newDriverPayout,
        status: 'pending', // Reset to pending
        updated_at: new Date().toISOString(),
      })
      .eq('id', bookingId)
      .eq('status', 'pending'); // Only update if still pending

    if (error) {
      return { success: false, error: error.message };
    }

    return { success: true, error: null };
  } catch (err: any) {
    return { success: false, error: err.message };
  }
}
