// Customer App - Bookings API Helper
// Handles booking creation, fetching, subscriptions, and cancellation

import { supabase } from "./supabase";
import type { Booking, ReceiverDetails, SelectedVehicle } from "@/types/type";

// =====================================================
// BOOKING CREATION
// =====================================================

export interface CreateBookingParams {
  customerId: string;
  originAddress: string;
  originLatitude: number;
  originLongitude: number;
  destinationAddress: string;
  destinationLatitude: number;
  destinationLongitude: number;
  vehicle: SelectedVehicle;
  receiverDetails: ReceiverDetails;
  goodsDescription?: string;
  tipAmount?: number;
  fareMultiplier?: number;
}

// Generate unique booking number
function generateBookingNumber(): string {
  const timestamp = Date.now().toString(36).toUpperCase();
  const random = Math.random().toString(36).substring(2, 6).toUpperCase();
  return `CARTR-${timestamp}-${random}`;
}

// Generate 4-digit OTP
function generateOTP(): string {
  return Math.floor(1000 + Math.random() * 9000).toString();
}

/**
 * Create a new booking in the database
 */
export async function createBooking(params: CreateBookingParams): Promise<{
  data: Booking | null;
  error: string | null;
}> {
  try {
    const {
      customerId,
      vehicle,
      receiverDetails,
      goodsDescription,
      tipAmount = 0,
      fareMultiplier = 1.0,
    } = params;

    // Calculate driver payout
    const driverPayout = (vehicle.total_fare * fareMultiplier) + tipAmount;

    const bookingData = {
      booking_number: generateBookingNumber(),
      customer_id: customerId,
      origin_address: params.originAddress,
      origin_latitude: params.originLatitude,
      origin_longitude: params.originLongitude,
      destination_address: params.destinationAddress,
      destination_latitude: params.destinationLatitude,
      destination_longitude: params.destinationLongitude,
      vehicle_type: vehicle.vehicle_type,
      estimated_distance: vehicle.distance_km,
      estimated_duration: vehicle.duration_minutes,
      base_fare: vehicle.base_fare,
      distance_fare: vehicle.distance_fare,
      time_fare: vehicle.time_fare,
      surge_multiplier: vehicle.surge_multiplier,
      total_fare: vehicle.total_fare,
      tip_amount: tipAmount,
      fare_multiplier: fareMultiplier,
      driver_payout: driverPayout,
      pickup_otp: generateOTP(),
      // delivery_otp is auto-generated by database trigger
      receiver_name: receiverDetails.name,
      receiver_phone: receiverDetails.phone,
      goods_description: goodsDescription || null,
      status: 'pending',
      payment_status: 'pending',
      payment_method: 'cash', // Default to cash, can be changed later
    };

    const { data, error } = await supabase
      .from('bookings')
      .insert(bookingData)
      .select()
      .single();

    if (error) {
      console.error('Error creating booking:', error);
      return { data: null, error: error.message };
    }

    return { data: data as Booking, error: null };
  } catch (err: any) {
    console.error('Booking creation failed:', err);
    return { data: null, error: err.message || 'Failed to create booking' };
  }
}

