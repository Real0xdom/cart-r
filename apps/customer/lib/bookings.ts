/**
 * Get a single booking by ID with driver details
 */
export async function getBookingById(bookingId: string): Promise<{
  data: Booking | null;
  error: string | null;
}> {
  try {
    const { data, error } = await supabase
      .from('bookings')
      .select(`
        *,
        driver:drivers(
          id,
          vehicle_number,
          vehicle_model,
          vehicle_color,
          rating,
          current_latitude,
          current_longitude,
          user:users(name, phone, avatar_url)
        )
      `)
      .eq('id', bookingId)
      .single();

    if (error) {
      return { data: null, error: error.message };
    }

    return { data: data as Booking, error: null };
  } catch (err: any) {
    return { data: null, error: err.message };
  }
}

/**
 * Get all bookings for a customer (history)
 */
export async function getCustomerBookings(customerId: string): Promise<{
  data: Booking[];
  error: string | null;
}> {
  try {
    const { data, error } = await supabase
      .from('bookings')
      .select(`
        *,
        driver:drivers(
          id,
          vehicle_number,
          vehicle_model,
          vehicle_color,
          rating,
          user:users(name, phone, avatar_url)
        )
      `)
      .eq('customer_id', customerId)
      .order('created_at', { ascending: false });

    if (error) {
      return { data: [], error: error.message };
    }

    return { data: data as Booking[], error: null };
  } catch (err: any) {
    return { data: [], error: err.message };
  }
}

